"""Human-readable output with Rich."""
from __future__ import annotations

from rich.console import Console
from rich.markup import escape
from rich.table import Table

from .diff import Change
from .models import CheckResult, Rule
from .trace import TraceEvent

STYLE = {"error": "bold red", "warning": "yellow", "info": "cyan"}
LABEL = {"error": "ERROR", "warning": "WARN ", "info": "INFO "}


def print_result(console: Console, r: CheckResult, verbose: bool = True) -> None:
    console.print(f"[bold]{escape(r.path)}[/bold]")
    if r.summary:
        console.print(f"  Format: {escape(r.summary)}")
    if not r.findings:
        console.print("  [green]OK[/green]  no problems found\n")
        return
    for f in r.findings:
        sev = f.severity
        loc = f"  ({escape(f.location)})" if f.location else ""
        console.print(f"  [{STYLE[sev]}][{LABEL[sev]}][/{STYLE[sev]}] [bold]{f.rule.id}[/bold]  "
                      f"{escape(f.rule.title)}{loc}")
        # A grid keeps wrapped lines aligned under their column instead of falling back to column 0.
        grid = Table.grid(padding=(0, 1))
        grid.add_column(width=9, no_wrap=True)
        grid.add_column(style="dim", no_wrap=True)
        grid.add_column(ratio=1)
        grid.add_row("", "", escape(f.message))
        if verbose:
            grid.add_row("", "Why it matters:", escape(f.rule.why))
            grid.add_row("", "Likely cause:", escape(f.rule.cause))
            grid.add_row("", "Fix:", escape(f.rule.fix))
        console.print(grid)
    console.print(f"  {r.errors} error(s), {r.warnings} warning(s)  (exit code {r.exit_code})\n")


def print_rules(console: Console, rules: list[Rule]) -> None:
    table = Table(show_lines=False)
    table.add_column("ID", style="bold")
    table.add_column("Format")
    table.add_column("Severity")
    table.add_column("Title")
    for r in rules:
        table.add_row(r.id, r.fmt, f"[{STYLE[r.severity]}]{r.severity}[/]", r.title)
    console.print(table)


def rules_markdown(rules: list[Rule]) -> str:
    lines = ["# Payload Doctor rule catalogue", "",
             "Generated by `pdoc rules --markdown`. Each rule explains why the problem matters, its likely cause "
             "and the fix, so this file doubles as a support knowledge base.", ""]
    current = None
    for r in rules:
        if r.fmt != current:
            current = r.fmt
            lines += [f"## {current.upper()}", ""]
        lines += [f"### {r.id}: {r.title}", "",
                  f"- **Severity:** {r.severity}",
                  f"- **Why it matters:** {r.why}",
                  f"- **Likely cause:** {r.cause}",
                  f"- **Fix:** {r.fix}", ""]
    return "\n".join(lines)


def print_trace(console: Console, txn: str, events: list[TraceEvent], summary: dict) -> None:
    console.print(f"[bold]Transaction {escape(txn)}[/bold]")
    if not events:
        console.print("  [yellow]No log lines mention this transaction ID.[/yellow]")
        return
    for e in events:
        style = STYLE["error"] if e.is_error else STYLE["warning"] if e.level == "WARNING" else ""
        t = e.raw_time[11:23] if len(e.raw_time) >= 19 else (e.raw_time or "--")
        line = f"  {t:<12}  {e.level:<8} {escape(e.message)}  [dim]{escape(e.source)}[/dim]"
        console.print(f"[{style}]{line}[/{style}]" if style else line)
    status_style = {"FAILED": "bold red", "OK": "bold green", "RECOVERED": "bold yellow"}.get(summary["status"], "")
    console.print()
    console.print(f"  Status:   [{status_style}]{summary['status']}[/{status_style}]")
    if summary.get("duration_seconds") is not None:
        console.print(f"  Duration: {summary['duration_seconds']:.1f}s over {summary['events']} log line(s)")
    if summary.get("retries"):
        console.print(f"  Retries:  {summary['retries']}")
    if summary.get("last_error"):
        console.print(f"  Last error: {escape(summary['last_error'])}  [dim]({escape(summary['last_error_source'])})[/dim]")


def print_diff(console: Console, fmt: str, changes: list[Change]) -> None:
    console.print(f"[bold]Format:[/bold] {fmt}   [bold]{len(changes)} difference(s)[/bold]")
    for c in changes:
        if c.kind == "changed":
            console.print(f"  [yellow]~[/yellow] {escape(c.location)}: {escape(repr(c.old))} -> {escape(repr(c.new))}")
        elif c.kind == "added":
            console.print(f"  [green]+[/green] {escape(c.location)}: {escape(str(c.new))}")
        else:
            console.print(f"  [red]-[/red] {escape(c.location)}: {escape(str(c.old))}")
